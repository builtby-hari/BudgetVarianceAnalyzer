# light and dark palettes. Navy and teal follow the shared README style. Warm (unfavorable),
# muted (budget), and panel (neutral cells) are the extra colors the charts need.
THEMES = {
    "light": {"bg": "#ffffff", "text": "#334155", "grid": "#cbd5e1", "navy": "#1f3a5f", "teal": "#14b8a6",
              "warm": "#c2410c", "muted": "#94a3b8", "panel": "#f1f5f9"},
    "dark": {"bg": None, "text": "#e2e8f0", "grid": "#475569", "navy": "#60a5fa", "teal": "#2dd4bf",
             "warm": "#fb923c", "muted": "#64748b", "panel": "#1e293b"},
}


def _pal(dark):
    return THEMES["dark" if dark else "light"]


def _ticks(lo, hi, n=5):
    raw = (hi - lo) / n
    mag = 10 ** math.floor(math.log10(raw))
    step = next(m * mag for m in (1, 2, 2.5, 5, 10) if m * mag >= raw)
    t, out = math.ceil(lo / step - 1e-9) * step, []
    while t <= hi + 1e-9:
        out.append(round(t, 10))
        t += step
    return out


def _open(w, h, pal, title, subtitle):
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{escape(title)}">']
    if pal["bg"]:
        p.append(f'<rect width="{w}" height="{h}" fill="{pal["bg"]}"/>')
    p.append(f'<text x="{w/2}" y="28" text-anchor="middle" font-size="16" font-weight="bold" fill="{pal["text"]}" {FONT}>{escape(title)}</text>')
    p.append(f'<text x="{w/2}" y="45" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>{escape(subtitle)}</text>')
    return p


def _frame(title, subtitle, ylabel, lo, hi, yfmt, pal, h=H, b=B, right=W - R):
    p = _open(W, h, pal, title, subtitle)
    ys = lambda v: h - b - (v - lo) / (hi - lo) * (h - b - T)
    for v in _ticks(lo, hi):
        p.append(f'<line x1="{L}" x2="{right}" y1="{ys(v):.1f}" y2="{ys(v):.1f}" stroke="{pal["grid"]}" stroke-width="0.8"/>')
        p.append(f'<text x="{L-8}" y="{ys(v)+4:.1f}" text-anchor="end" font-size="11" fill="{pal["text"]}" {FONT}>{yfmt(v)}</text>')
    p.append(f'<line x1="{L}" x2="{L}" y1="{T}" y2="{h-b}" stroke="{pal["text"]}"/>')
    p.append(f'<line x1="{L}" x2="{right}" y1="{h-b}" y2="{h-b}" stroke="{pal["text"]}"/>')
    p.append(f'<text transform="translate(18 {(T+h-b)/2}) rotate(-90)" text-anchor="middle" font-size="12" fill="{pal["text"]}" {FONT}>{escape(ylabel)}</text>')
    return p, ys


def _fmt_m(v):
    return f"${v/1e6:.1f}M" if abs(v) >= 1e6 else f"${v/1e3:,.0f}K"


def _fmt_signed(v):
    return ("-" if v < 0 else "") + _fmt_m(abs(v))


def _split_label(label, limit=14):
    """Up to two lines for an axis label, split at the space nearest the middle."""
    if len(label) <= limit or " " not in label:
        return [label]
    words = label.split(" ")
    best = min(range(1, len(words)), key=lambda i: abs(len(" ".join(words[:i])) - len(label) / 2))
    return [" ".join(words[:best]), " ".join(words[best:])]


def _legend(p, pal, y, items):
    x = L
    for color, text, dash in items:
        if dash:
            p.append(f'<line x1="{x}" x2="{x+24}" y1="{y-4}" y2="{y-4}" stroke="{color}" stroke-width="2.2" stroke-dasharray="6 4"/>')
            tx = x + 30
            x += 30 + 6.4 * len(text) + 20
        else:
            p.append(f'<rect x="{x}" y="{y-9}" width="10" height="10" fill="{color}"/>')
            tx = x + 15
            x += 15 + 6.4 * len(text) + 22
        p.append(f'<text x="{tx}" y="{y}" font-size="11" fill="{pal["text"]}" {FONT}>{escape(text)}</text>')


def _rotated_label(p, pal, cx, cy, label):
    shown = label if len(label) <= 34 else label[:33] + "..."
    p.append(f'<text transform="translate({cx:.1f} {cy}) rotate(35)" font-size="10.5" fill="{pal["text"]}" {FONT}>{escape(shown)}</text>')


def _value_label(p, pal, x, y, text):
    p.append(f'<text x="{x:.1f}" y="{y:.1f}" text-anchor="middle" font-size="10.5" fill="{pal["text"]}" {FONT}>{escape(text)}</text>')


def _period(analysis):
    return f"through {analysis.through} ({analysis.months_elapsed} months)"


def waterfall_svg(analysis, n_drivers=6, dark=False):
    """YTD budget -> top drivers -> other -> YTD actual, expense lines only. The y-axis is truncated to show the steps.
    Not embedded in the README any more; the HTML report uses it."""
    pal = _pal(dark)
    lines = top_drivers(analysis.expense_lines, n_drivers)
    other = analysis.total.var - sum(r.var for r in lines)
    steps = [(f"{r.cost_center}: {r.category}", r.var) for r in lines]
    steps.append(("All Other Lines", other))
    b, level, levels = analysis.total.ytd_budget, analysis.total.ytd_budget, []
    for _, v in steps:
        levels.append((level, level + v))
        level += v
    allv = [b, analysis.total.ytd_actual] + [x for pair in levels for x in pair]
    span = max(allv) - min(allv)
    lo, hi = min(allv) - span * 0.35, max(allv) + span * 0.12
    WH, WB = 540, 175
    p, ys = _frame(f"YTD Budget to Actual by Driver (Through {analysis.through})",
                   f"{SYNTHETIC}. Axis truncated, not from zero.", "YTD Spend", lo, hi, _fmt_m, pal, WH, WB)
    cols = len(steps) + 2
    slot = (W - L - R) / cols
    bw = slot * 0.62

    def bar(i, top, bottom, color, label, value_text):
        x = L + slot * i + (slot - bw) / 2
        y1, y2 = ys(max(top, bottom)), ys(min(top, bottom))
        p.append(f'<rect x="{x:.1f}" y="{y1:.1f}" width="{bw:.1f}" height="{max(y2-y1, 1.5):.1f}" fill="{color}"/>')
        _value_label(p, pal, x + bw / 2, y1 - 5, value_text)
        _rotated_label(p, pal, x + bw / 2, WH - WB + 14, label)

    bar(0, b, lo, pal["muted"], "YTD Budget", _fmt_m(b))
    for i, ((label, v), (a, z)) in enumerate(zip(steps, levels), start=1):
        bar(i, a, z, pal["warm"] if v > 0 else pal["teal"], label, f"{'+' if v >= 0 else '-'}{money(v)}")
        px = L + slot * (i - 1) + (slot + bw) / 2
        p.append(f'<line x1="{px:.1f}" x2="{L+slot*i+(slot-bw)/2:.1f}" y1="{ys(a):.1f}" y2="{ys(a):.1f}" stroke="{pal["text"]}" stroke-dasharray="3 3" stroke-width="0.8"/>')
    bar(cols - 1, analysis.total.ytd_actual, lo, pal["navy"], "YTD Actual", _fmt_m(analysis.total.ytd_actual))
    _legend(p, pal, WH - 12, [(pal["warm"], "Over Budget (Unfavorable)", False), (pal["teal"], "Under Budget (Favorable)", False)])
    p.append('</svg>')
    return "\n".join(p)


def monthly_svg(analysis, dark=False):
    """Total monthly budget vs actual, with the run-rate projection dashed for open months. Used by the HTML report."""
    pal = _pal(dark)
    m = analysis.monthly
    vals = [r["budget"] for r in m] + [r["actual"] for r in m if r["actual"] is not None] + \
           [r["projection"] for r in m if r["projection"] is not None]
    lo = math.floor(min(vals) * 0.9 / 1e5) * 1e5
    hi = max(vals) * 1.05
    p, ys = _frame(f"Monthly Budget vs Actual, Total (FY{analysis.year})",
                   f"{SYNTHETIC}. Axis truncated, not from zero.", "Monthly Spend", lo, hi, _fmt_m, pal)
    step = (W - L - R) / 12
    xs = lambda i: L + step * (i + 0.5)
    for i in range(12):
        p.append(f'<text x="{xs(i):.1f}" y="{H-B+19}" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>{MONTH_ABBR[i]}</text>')

    def path(idx, key, color):
        pts = [(xs(i), ys(m[i][key])) for i in idx]
        d = " ".join(("M" if j == 0 else "L") + f"{x:.1f} {y:.1f}" for j, (x, y) in enumerate(pts))
        p.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="2.2"/>')
        for x, y in pts:
            p.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3.2" fill="{color}"/>')

    n = analysis.months_elapsed
    path(range(12), "budget", pal["muted"])
    path(range(n), "actual", pal["navy"])
    if n < 12:
        pts = [(xs(n - 1), ys(m[n - 1]["actual"]))] + [(xs(i), ys(m[i]["projection"])) for i in range(n, 12)]
        d = " ".join(("M" if j == 0 else "L") + f"{x:.1f} {y:.1f}" for j, (x, y) in enumerate(pts))
        p.append(f'<path d="{d}" fill="none" stroke="{pal["navy"]}" stroke-width="2.2" stroke-dasharray="6 4"/>')
    _legend(p, pal, H - 14, [(pal["muted"], "Budget", False), (pal["navy"], "Actual", False),
                             (pal["navy"], "Run-Rate Projection", True)])
    p.append('</svg>')
    return "\n".join(p)


def bridge_svg(analysis, dark=False):
    """Operating income bridge: budget OI -> one favorable step per category -> actual OI.
    The y-axis is truncated (the title says where it starts); the total bars hang from the axis floor."""
    pal = _pal(dark)
    steps = bridge_steps(analysis)
    levels, running = [], 0.0
    for label, value, kind in steps:
        if kind == "total":
            start, end, running = 0.0, value, value
        else:
            start, end = running, running + value
            running = end
        levels.append((label, start, end, kind, value))
    real = [v for _, a, z, kind, _ in levels for v in ((z,) if kind == "total" else (a, z))]
    lo_raw, hi_raw = min(real), max(real)
    span = (hi_raw - lo_raw) or 1.0
    raw_step = span * 1.5 / 5
    mag = 10 ** math.floor(math.log10(raw_step))
    step = next(m * mag for m in (1, 2, 2.5, 5, 10) if m * mag >= raw_step)
    lo = math.floor((lo_raw - span * 0.25) / step) * step
    hi = math.ceil((hi_raw + span * 0.10) / step) * step
    WH, WB = 540, 175
    p, ys = _frame(f"Operating Income Bridge: Budget to Actual (YTD; Axis Starts at {lo:,.0f})",
                   f"{SYNTHETIC}, {_period(analysis)}. Axis truncated, not from zero.",
                   "Operating Income, YTD", lo, hi, _fmt_signed, pal, WH, WB)
    slot = (W - L - R) / len(levels)
    bw = slot * 0.62

    def bar(i, top, bottom, color, label, value_text):
        x = L + slot * i + (slot - bw) / 2
        y1, y2 = ys(max(top, bottom)), ys(min(top, bottom))
        p.append(f'<rect x="{x:.1f}" y="{y1:.1f}" width="{bw:.1f}" height="{max(y2-y1, 1.5):.1f}" fill="{color}"/>')
        _value_label(p, pal, x + bw / 2, y1 - 5, value_text)
        _rotated_label(p, pal, x + bw / 2, WH - WB + 14, label)

    prev_end = None
    for i, (label, a, z, kind, value) in enumerate(levels):
        if kind == "total":
            bar(i, z, lo, pal["muted"] if i == 0 else pal["navy"], label, _fmt_signed(value))
        else:
            bar(i, a, z, pal["teal"] if value >= 0 else pal["warm"], label, f"{'+' if value >= 0 else '-'}{money(value)}")
        if prev_end is not None:
            x0 = L + slot * (i - 1) + (slot + bw) / 2
            p.append(f'<line x1="{x0:.1f}" x2="{L+slot*i+(slot-bw)/2:.1f}" y1="{ys(prev_end):.1f}" y2="{ys(prev_end):.1f}" stroke="{pal["text"]}" stroke-dasharray="3 3" stroke-width="0.8"/>')
        prev_end = z
    _legend(p, pal, WH - 12, [(pal["teal"], "Favorable (Raises Operating Income)", False),
                              (pal["warm"], "Unfavorable (Lowers Operating Income)", False)])
    p.append('</svg>')
    return "\n".join(p)


def line_items_svg(analysis, dark=False):
    """YTD budget vs actual by expense line item, summed across cost centers, sorted by budget."""
    pal = _pal(dark)
    groups = {}
    for r in analysis.expense_lines:
        g = groups.setdefault(r.category, [0.0, 0.0])
        g[0] += r.ytd_budget
        g[1] += r.ytd_actual
    items = sorted(groups.items(), key=lambda kv: (-kv[1][0], kv[0]))
    top = max(max(b, a) for _, (b, a) in items)
    p, ys = _frame("YTD Budget vs Actual by Line Item (Expense, All Cost Centers)",
                   f"{SYNTHETIC}, {_period(analysis)}", "YTD Spend", 0, top * 1.15, _fmt_m, pal)
    slot = (W - L - R) / len(items)
    bw = slot * 0.3
    for i, (name, (b, a)) in enumerate(items):
        cx = L + slot * (i + 0.5)
        for x, v, color in ((cx - bw - 1.5, b, pal["muted"]), (cx + 1.5, a, pal["navy"])):
            p.append(f'<rect x="{x:.1f}" y="{ys(v):.1f}" width="{bw:.1f}" height="{ys(0)-ys(v):.1f}" fill="{color}"/>')
            _value_label(p, pal, x + bw / 2, ys(v) - 5, _fmt_m(v))
        for k, line in enumerate(_split_label(name)):
            p.append(f'<text x="{cx:.1f}" y="{H-B+19+k*14}" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>{escape(line)}</text>')
    _legend(p, pal, H - 14, [(pal["muted"], "Budget", False), (pal["navy"], "Actual", False)])
    p.append('</svg>')
    return "\n".join(p)


def _mix(c1, c2, t):
    a = [int(c1[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(c2[i:i + 2], 16) for i in (1, 3, 5)]
    return "#%02x%02x%02x" % tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def _heat(v, lim, pal):
    """Diverging fill: teal under budget, panel at zero, warm over budget."""
    t = max(-1.0, min(1.0, v / lim))
    return _mix(pal["panel"], pal["teal"], -t) if t < 0 else _mix(pal["panel"], pal["warm"], t)


def _ink(color):
    r, g, b = (int(color[i:i + 2], 16) for i in (1, 3, 5))
    return "#0f172a" if (0.299 * r + 0.587 * g + 0.114 * b) / 255 > 0.55 else "#f8fafc"


def heatmap_svg(analysis, dark=False):
    """Variance % vs budget by expense cost center (rows) and closed month (columns), plus the expense total."""
    pal = _pal(dark)
    n = analysis.months_elapsed

    def pct(m):
        return (m["actual"] - m["budget"]) / abs(m["budget"]) if m["budget"] else None

    rows = [(r.cost_center, [pct(m) for m in analysis.cc_monthly[r.cost_center][:n]]) for r in analysis.cost_centers]
    rows.append(("Total", [pct(m) for m in analysis.monthly[:n]]))
    vals = [v for _, cells in rows for v in cells if v is not None]
    lim = math.ceil(max(abs(v) for v in vals) * 20) / 20
    LABEL_W, TOP, CELL_H, GAP = 150, 84, 46, 8
    cell_w = (W - LABEL_W - R - 10) / n
    legend_y = TOP + len(rows) * CELL_H + GAP + 56
    h = legend_y + 36
    p = _open(W, h, pal, "Variance % vs Budget by Cost Center and Month (Expense)",
              f"{SYNTHETIC}, {_period(analysis)}. Teal is under budget, orange is over budget.")
    p.insert(1, f'<defs><linearGradient id="heatgrad" x1="0" x2="1" y1="0" y2="0">'
                f'<stop offset="0" stop-color="{pal["teal"]}"/><stop offset="0.5" stop-color="{pal["panel"]}"/>'
                f'<stop offset="1" stop-color="{pal["warm"]}"/></linearGradient></defs>')
    for j, mabbr in enumerate(MONTH_ABBR[:n]):
        p.append(f'<text x="{LABEL_W + cell_w*(j+0.5):.1f}" y="{TOP-12}" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>{mabbr}</text>')
    for name, cells in rows:
        i = [r for r, _ in rows].index(name)
        y = TOP + i * CELL_H + (GAP if name == "Total" else 0)
        if name == "Total":
            p.append(f'<line x1="{L-60}" x2="{W-R}" y1="{y-GAP/2}" y2="{y-GAP/2}" stroke="{pal["grid"]}" stroke-width="0.8"/>')
        weight = "bold" if name == "Total" else "normal"
        p.append(f'<text x="{LABEL_W-10}" y="{y+CELL_H/2+4:.1f}" text-anchor="end" font-size="12" font-weight="{weight}" fill="{pal["text"]}" {FONT}>{escape(name)}</text>')
        for j, v in enumerate(cells):
            x = LABEL_W + cell_w * j
            fill = pal["grid"] if v is None else _heat(v, lim, pal)
            ink = pal["text"] if v is None else _ink(fill)
            p.append(f'<rect x="{x+1.5:.1f}" y="{y+1.5:.1f}" width="{cell_w-3:.1f}" height="{CELL_H-3:.1f}" rx="4" fill="{fill}"/>')
            label = "n/a" if v is None else f"{v*100:+.1f}%"
            p.append(f'<text x="{x+cell_w/2:.1f}" y="{y+CELL_H/2+4:.1f}" text-anchor="middle" font-size="12" fill="{ink}" {FONT}>{label}</text>')
    lx, lw = L, 300
    p.append(f'<rect x="{lx}" y="{legend_y}" width="{lw}" height="10" fill="url(#heatgrad)" rx="2"/>')
    p.append(f'<text x="{lx}" y="{legend_y+26}" font-size="11" fill="{pal["text"]}" {FONT}>-{lim*100:.0f}%</text>')
    p.append(f'<text x="{lx+lw/2}" y="{legend_y+26}" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>0</text>')
    p.append(f'<text x="{lx+lw}" y="{legend_y+26}" text-anchor="end" font-size="11" fill="{pal["text"]}" {FONT}>+{lim*100:.0f}%</text>')
    p.append(f'<text x="{lx+lw+20}" y="{legend_y+9}" font-size="11" fill="{pal["text"]}" {FONT}>Color saturates at +/-{lim*100:.0f}%.</text>')
    p.append('</svg>')
    return "\n".join(p)


def cumulative_svg(analysis, dark=False):
    """Cumulative YTD budget vs actual for the expense total, through the last closed month."""
    pal = _pal(dark)
    n = analysis.months_elapsed
    cum_b, cum_a = [], []
    cb = ca = 0.0
    for m in analysis.monthly[:n]:
        cb += m["budget"]
        ca += m["actual"]
        cum_b.append(cb)
        cum_a.append(ca)
    lo = math.floor(min(cum_b) * 0.97 / 1e5) * 1e5
    hi = math.ceil(max(cum_a + cum_b) * 1.01 / 1e5) * 1e5
    right = W - 175
    p, ys = _frame("Cumulative YTD Budget vs Actual (Expense, Total)",
                   f"{SYNTHETIC}, {_period(analysis)}. Axis truncated, not from zero.",
                   "Cumulative Spend", lo, hi, _fmt_m, pal, right=right)
    xs = lambda i: L + (right - L - 20) * (i / max(n - 1, 1))
    for i in range(n):
        p.append(f'<text x="{xs(i):.1f}" y="{H-B+19}" text-anchor="middle" font-size="11" fill="{pal["text"]}" {FONT}>{MONTH_ABBR[i]}</text>')
    for vals, color in ((cum_b, pal["muted"]), (cum_a, pal["navy"])):
        pts = [(xs(i), ys(v)) for i, v in enumerate(vals)]
        d = " ".join(("M" if j == 0 else "L") + f"{x:.1f} {y:.1f}" for j, (x, y) in enumerate(pts))
        p.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="2.4"/>')
        for x, y in pts:
            p.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3.2" fill="{color}"/>')
    ex = xs(n - 1) + 12
    eb, ea = cum_b[-1], cum_a[-1]
    gap = ea - eb
    # the two end points sit close together, so the labels are stacked with fixed spacing
    ya = ys(ea) + 4
    yb = max(ys(eb) + 4, ya + 20)
    p.append(f'<text x="{ex:.1f}" y="{ya:.1f}" font-size="12" font-weight="bold" fill="{pal["navy"]}" {FONT}>Actual {_fmt_m(ea)}</text>')
    p.append(f'<text x="{ex:.1f}" y="{yb:.1f}" font-size="12" fill="{pal["muted"]}" {FONT}>Budget {_fmt_m(eb)}</text>')
    p.append(f'<text x="{ex:.1f}" y="{yb+18:.1f}" font-size="11" fill="{pal["warm"] if gap > 0 else pal["teal"]}" {FONT}>'
             f'{"+" if gap >= 0 else "-"}{money(gap)} ({abs(gap)/eb*100:.1f}%) vs Budget</text>')
    _legend(p, pal, H - 14, [(pal["muted"], "Budget", False), (pal["navy"], "Actual", False)])
    p.append('</svg>')
    return "\n".join(p)


def flagged_svg(analysis, dark=False, n=10):
    """Largest line variances: bar length = variance $, color = favorable or unfavorable.
    Lines that breach materiality are solid and marked *; the others are faded."""
    pal = _pal(dark)
    rows = top_drivers(analysis.lines, n)
    m = max(abs(r.var) for r in rows)
    ROW, TOP_Y = 34, 96
    h = TOP_Y + len(rows) * ROW + 70
    p = _open(W, h, pal, "Flagged Line Items: Largest Variances, Favorable and Unfavorable",
              f"{SYNTHETIC}, {_period(analysis)}. * = material (over both the $ and % thresholds).")
    x0, half = 470, 150
    p.append(f'<line x1="{x0}" x2="{x0}" y1="{TOP_Y-10}" y2="{TOP_Y + len(rows)*ROW - 8}" stroke="{pal["text"]}"/>')
    for i, r in enumerate(rows):
        y = TOP_Y + i * ROW
        color = pal["warm"] if r.status == "U" else (pal["teal"] if r.status == "F" else pal["muted"])
        length = abs(r.var) / m * half
        x = x0 if r.var >= 0 else x0 - length
        opacity = "1" if r.material else "0.4"
        p.append(f'<rect x="{x:.1f}" y="{y}" width="{max(length, 1.5):.1f}" height="18" fill="{color}" opacity="{opacity}"/>')
        label = f"{r.cost_center} / {r.category}" + (" *" if r.material else "")
