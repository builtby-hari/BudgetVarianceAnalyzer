def cli_output(args):
    """Real stdout of cli.py run with the given arguments."""
    if ROOT not in sys.path:
        sys.path.insert(0, ROOT)
    import cli
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        cli.main(list(args))
    return buf.getvalue()


def sample_output_svg(dark=False, args=("--no-commentary",)):
    """Terminal-window render of real CLI output, wrapped to fit the window."""
    pal = _pal(dark)
    lines = []
    for raw in cli_output(args).rstrip("\n").split("\n"):
        if len(raw) <= 130:
            lines.append(raw)
        else:
            lines.extend(textwrap.wrap(raw, 130, subsequent_indent="    ", break_on_hyphens=False) or [""])
    cmd = "$ python3 cli.py " + " ".join(args)
    lh, body_top, w = 19, 60, 1180
    h = body_top + lh * (len(lines) + 2) + 22
    if dark:
        win, bar, edge, ink = "#0f172a", "#1e293b", "#334155", pal["text"]
    else:
        win, bar, edge, ink = "#f8fafc", "#e2e8f0", "#cbd5e1", "#1e293b"
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 {h+20}" width="1200" height="{h+20}" role="img" aria-label="Terminal output of the budget variance CLI">',
         f'<rect x="10" y="10" width="{w}" height="{h}" rx="12" fill="{win}" stroke="{edge}"/>',
         f'<path d="M10 22 Q10 10 22 10 L{10+w-12} 10 Q{10+w} 10 {10+w} 22 L{10+w} 44 L10 44 Z" fill="{bar}"/>',
         '<circle cx="34" cy="27" r="6" fill="#ff5f57"/><circle cx="54" cy="27" r="6" fill="#febc2e"/><circle cx="74" cy="27" r="6" fill="#28c840"/>',
         f'<text x="600" y="31" text-anchor="middle" font-size="12" fill="{ink}" {FONT}>bva: Budget Variance Analyzer</text>',
         f'<text x="30" y="{body_top}" font-size="13" font-weight="bold" fill="{pal["teal"]}" xml:space="preserve" {MONO}>{escape(cmd)}</text>']
    for i, line in enumerate(lines):
        y = body_top + lh * (i + 2)
        p.append(f'<text x="30" y="{y}" font-size="13" fill="{ink}" xml:space="preserve" {MONO}>{escape(line)}</text>')
