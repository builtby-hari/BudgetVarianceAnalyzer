def write_svgs(analysis, outdir):
    """CLI --charts: write the waterfall and monthly charts, plus the operating-income bridge when the data
    has revenue lines (light theme). Returns the file names written."""
    os.makedirs(outdir, exist_ok=True)
    charts = [("waterfall.svg", waterfall_svg(analysis)), ("monthly.svg", monthly_svg(analysis))]
    if analysis.has_revenue:
        charts.append(("bridge.svg", bridge_svg(analysis)))
    for name, svg in charts:
        with open(os.path.join(outdir, name), "w") as f:
            f.write(svg)
    return [name for name, _ in charts]


def sample_analyses(root=ROOT):
    """(expense analysis on the narrow sample, wide analysis with revenue) from the bundled synthetic data."""
    data = os.path.join(root, "data")
    b, a, kinds = load_dataset(os.path.join(data, "budget.csv"), os.path.join(data, "actuals.csv"))
    expense = analyze(b, a, kinds=kinds)
    wb, wa, wk = load_wide(os.path.join(data, "sample_wide.csv"))
    wide = analyze(wb, wa, kinds=wk)
    return expense, wide


def build_docs(outdir, root=ROOT):
    """Write every README visual, light and dark. Returns the file names written."""
    os.makedirs(outdir, exist_ok=True)
    expense, wide = sample_analyses(root)
    jobs = {
        "bridge": lambda d: bridge_svg(wide, d),
        "line-items": lambda d: line_items_svg(expense, d),
        "heatmap": lambda d: heatmap_svg(expense, d),
        "cumulative": lambda d: cumulative_svg(expense, d),
        "flagged": lambda d: flagged_svg(expense, d),
        "sample-output": lambda d: sample_output_svg(d),
        "banner": lambda d: banner_svg(d),
    }
    written = []
    for name, make in jobs.items():
        for dark in (False, True):
            fname = f"{name}-dark.svg" if dark else f"{name}.svg"
            with open(os.path.join(outdir, fname), "w") as f:
                f.write(make(dark))
            written.append(fname)
    return written


